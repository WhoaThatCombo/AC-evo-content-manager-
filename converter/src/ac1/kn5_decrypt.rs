//! CSP KN5 encryption (encVersion 1-3) decryption.
//!
//! Ported from Kn5Decrypt (GPL-3.0) by x4fab / ilja615.
//! Envelope: the original KN5 body, then a sidecar of encrypted textures and
//! vertex masks, then a 38-byte tail: 30-byte magic + sidecar_offset (u32) +
//! enc_version (u32).

use anyhow::{bail, Result};
use std::collections::HashMap;
use std::io::{Cursor, Read, Write};

const MAGIC: &[u8] = b"__AC_SHADERS_PATCH_KN5ENC_v1__";
const TAIL_LEN: usize = MAGIC.len() + 8;

/// Returns `Some((sidecar_offset, enc_version))` when the file has a CSP v1 envelope.
pub fn detect(data: &[u8]) -> Option<(u32, u32)> {
    if data.len() < TAIL_LEN + 32 {
        return None;
    }
    let tail_start = data.len() - TAIL_LEN;
    if &data[tail_start..tail_start + MAGIC.len()] != MAGIC {
        return None;
    }
    let off = u32::from_le_bytes(data[data.len() - 8..data.len() - 4].try_into().unwrap());
    let ver = u32::from_le_bytes(data[data.len() - 4..].try_into().unwrap());
    Some((off, ver))
}

/// Nothing to restore: no encrypted textures, and (envelope v2/3) the vertex
/// entries are tweak data the geometry doesn't need - the body is already plain.
/// (No Hesi cars: `met.user.u` + `ver.<mesh>/<count>.*` and real textures in the body.)
fn body_is_plain(sidecar: &HashMap<String, Vec<u8>>, enc_version: u32) -> bool {
    let encrypted_textures = sidecar.keys().any(|k| k.starts_with("tex.") && k.ends_with(".d"));
    sidecar.is_empty() || (!encrypted_textures && enc_version != 1)
}

/// Folder names the encrypting tool may have used for this file (its own
/// folder first, then up to two parents: a copy kept in "Enhanced/" or
/// "Original/" is salted with the track's name) and the sibling data.acd.
fn context_of(path: &std::path::Path) -> (Vec<String>, Option<Vec<u8>>) {
    let mut names = Vec::new();
    let mut cur = path.parent();
    for _ in 0..3 {
        let Some(d) = cur else { break };
        if let Some(n) = d.file_name() {
            names.push(n.to_string_lossy().into_owned());
        }
        cur = d.parent();
    }
    let acd = path.parent().and_then(|d| {
        std::fs::read_dir(d).ok()?.flatten().find(|e| e.file_name().to_string_lossy().eq_ignore_ascii_case("data.acd")).and_then(|e| std::fs::read(e.path()).ok())
    });
    (names, acd)
}

/// Candidate passwords: "car model/<folder>" lower-cased (the case the tool
/// salts with), then as written, each with the data.acd hash first when there is one.
fn salt_candidates(folders: &[String], acd: Option<&[u8]>) -> Vec<String> {
    let suffix = acd.map(|a| {
        use sha2::Digest;
        format!(":{}", base64_nopad(&sha2::Sha256::digest(a)))
    });
    let mut out: Vec<String> = Vec::new();
    for f in folders {
        let plain = format!("car model/{f}");
        for base in [plain.to_lowercase(), plain] {
            if let Some(sfx) = &suffix {
                out.push(format!("{base}{sfx}"));
            }
            out.push(base);
        }
    }
    let mut seen = std::collections::HashSet::new();
    out.retain(|x| seen.insert(x.clone()));
    out
}

/// Can this file be opened? `Ok(())` when nothing is encrypted in it or its
/// salt and keys resolve; `Err` says why not. Reads the file, does not rebuild it.
pub fn status(path: &std::path::Path) -> Result<()> {
    let data = std::fs::read(path)?;
    let Some((off, ver)) = detect(&data) else {
        bail!("the lock is not a CSP v1 envelope this tool knows")
    };
    if ver > 3 {
        bail!("CSP encVersion {ver} is not supported");
    }
    let sidecar = read_sidecar(&data, off as usize, data.len() - TAIL_LEN)?;
    if body_is_plain(&sidecar, ver) {
        return Ok(());
    }
    let (folders, acd) = context_of(path);
    if resolve_salt(&sidecar, &salt_candidates(&folders, acd.as_deref())).is_some() {
        return Ok(());
    }
    // say whether a key is simply missing from the table
    for k in sidecar.keys() {
        if k.ends_with(".k") && k.len() > 6 {
            let name = &k[4..k.len() - 2];
            if let (Some(kb), Some(iv)) = (sidecar.get(k), sidecar.get(&format!("{}.{}.i", &k[..3], name))) {
                if kb.len() >= 4 && iv.len() >= 4 {
                    let id = u32::from_le_bytes(kb[..4].try_into().unwrap()) ^ u32::from_le_bytes(iv[..4].try_into().unwrap());
                    if !KEY_TABLE.contains_key(&id) {
                        bail!("key 0x{id:08X} is not in the built-in key table");
                    }
                }
            }
        }
    }
    bail!("could not work out the per-file key")
}

/// kn5 bytes: memory-mapped when plain, the decrypted copy when CSP-encrypted.
pub enum Kn5Bytes {
    Map(memmap2::Mmap),
    Owned(Vec<u8>),
}

impl std::ops::Deref for Kn5Bytes {
    type Target = [u8];
    fn deref(&self) -> &[u8] {
        match self {
            Kn5Bytes::Map(m) => m,
            Kn5Bytes::Owned(v) => v,
        }
    }
}

/// Open a kn5 for reading, decrypting a CSP envelope when it has one.
pub fn open(path: &std::path::Path) -> Result<Kn5Bytes> {
    let f = std::fs::File::open(path)?;
    // SAFETY: read-only map of a file nobody writes while we convert
    let mapped = unsafe { memmap2::Mmap::map(&f)? };
    if detect(&mapped).is_none() {
        return Ok(Kn5Bytes::Map(mapped));
    }
    let (folders, acd) = context_of(path);
    Ok(Kn5Bytes::Owned(decrypt(&mapped, &folders, acd.as_deref())?))
}

/// Decrypt an encrypted KN5 and return the rebuilt plain KN5 bytes.
///
/// `folders` are the folder names to try as the salt. `acd_bytes` is the raw
/// `data.acd` content (if present). Only encVersion 1 produces a full
/// rebuilt KN5 with restored textures and geometry; 2-3 return the body
/// with textures restored but vertex masks not applied.
pub fn decrypt(data: &[u8], folders: &[String], acd_bytes: Option<&[u8]>) -> Result<Vec<u8>> {
    let (sidecar_offset, enc_version) = detect(data)
        .ok_or_else(|| anyhow::anyhow!("no CSP v1 envelope"))?;
    if enc_version > 3 {
        bail!("CSP encVersion {enc_version} is not supported");
    }
    let sidecar_end = data.len() - TAIL_LEN;
    let sidecar = read_sidecar(data, sidecar_offset as usize, sidecar_end)?;
    if body_is_plain(&sidecar, enc_version) {
        let body = &data[..sidecar_offset as usize];
        parse_kn5_body(body)?;
        return Ok(body.to_vec());
    }

    let salts = salt_candidates(folders, acd_bytes);

    let active_salt = resolve_salt(&sidecar, &salts)
        .ok_or_else(|| anyhow::anyhow!("could not work out the per-file key (a key missing from the table, or a renamed folder)"))?;

    let decrypted_textures = decrypt_textures(&sidecar, &active_salt)?;
    let decrypted_masks = decrypt_vertex_masks(&sidecar, &active_salt, enc_version)?;

    let body = &data[..sidecar_offset as usize];
    if enc_version == 1 {
        rebuild_kn5(body, &decrypted_textures, &decrypted_masks)
    } else {
        rebuild_kn5(body, &decrypted_textures, &HashMap::new())
    }
}

// ── sidecar ──────────────────────────────────────────────────────────

fn read_sidecar(data: &[u8], start: usize, end: usize) -> Result<HashMap<String, Vec<u8>>> {
    let mut map = HashMap::new();
    let mut pos = start;
    while pos < end {
        if pos + 4 > end { break; }
        let name_len = u32::from_le_bytes(data[pos..pos + 4].try_into().unwrap()) as usize;
        pos += 4;
        if pos + name_len > end { break; }
        let name = std::str::from_utf8(&data[pos..pos + name_len])
            .unwrap_or("")
            .to_string();
        pos += name_len;
        if pos + 4 > end { break; }
        let data_len = u32::from_le_bytes(data[pos..pos + 4].try_into().unwrap()) as usize;
        pos += 4;
        if pos + data_len > end { break; }
        if name.len() > 6 && name.as_bytes().get(3) == Some(&b'.') {
            let n = name.len();
            if n >= 2 && name.as_bytes()[n - 2] == b'.' {
                map.insert(name, data[pos..pos + data_len].to_vec());
            }
        }
        pos += data_len;
    }
    Ok(map)
}

// ── AES ──────────────────────────────────────────────────────────────

fn aes_decrypt(ciphertext: &[u8], iv: &[u8], k_raw: u32, car_key: &str) -> Result<Vec<u8>> {
    use aes::cipher::{BlockDecryptMut, KeyIvInit};
    type Aes256CbcDec = cbc::Decryptor<aes::Aes256>;

    let id = k_raw ^ u32::from_le_bytes(iv[..4].try_into().unwrap());
    let raw_key_mat = KEY_TABLE.get(&id)
        .ok_or_else(|| anyhow::anyhow!("key id 0x{id:08X} not in static store"))?;

    let mut source = Vec::with_capacity(4 + raw_key_mat.len());
    source.extend_from_slice(&id.to_le_bytes());
    source.extend_from_slice(&raw_key_mat[..]);

    let car_bytes = car_key.as_bytes();
    let klen = source.len() - 4;
    for (i, &b) in car_bytes.iter().enumerate() {
        source[4 + i % klen] ^= b;
    }

    let aes_key = &source[4..];
    let dec = Aes256CbcDec::new_from_slices(aes_key, iv)
        .map_err(|e| anyhow::anyhow!("AES init: {e}"))?;

    let mut buf = ciphertext.to_vec();
    let plain = dec
        .decrypt_padded_mut::<aes::cipher::block_padding::Pkcs7>(&mut buf)
        .map_err(|_| anyhow::anyhow!("AES decrypt failed (bad padding)"))?;
    Ok(plain.to_vec())
}

fn xor_in_place(dst: &mut [u8], src: &[u8]) {
    if src.is_empty() { return; }
    for (i, b) in dst.iter_mut().enumerate() {
        *b ^= src[i % src.len()];
    }
}

fn try_zlib_decompress(data: &[u8]) -> Option<Vec<u8>> {
    let mut decoder = flate2::read::ZlibDecoder::new(data);
    let mut out = Vec::new();
    decoder.read_to_end(&mut out).ok()?;
    Some(out)
}

// ── textures ─────────────────────────────────────────────────────────

fn decrypt_textures(
    sidecar: &HashMap<String, Vec<u8>>,
    car_key: &str,
) -> Result<HashMap<String, Vec<u8>>> {
    let mut result = HashMap::new();
    let mut tex_names: Vec<String> = Vec::new();
    for k in sidecar.keys() {
        if let Some(rest) = k.strip_prefix("tex.") {
            if let Some(name) = rest.strip_suffix(".k") {
                if !tex_names.contains(&name.to_string()) {
                    tex_names.push(name.to_string());
                }
            }
        }
    }

    for name in &tex_names {
        let Some(k_bytes) = sidecar.get(&format!("tex.{name}.k")) else { continue };
        let Some(iv) = sidecar.get(&format!("tex.{name}.i")) else { continue };
        let Some(cipher) = sidecar.get(&format!("tex.{name}.x")) else { continue };
        let Some(d_blob) = sidecar.get(&format!("tex.{name}.d")) else { continue };

        let k_raw = u32::from_le_bytes(k_bytes[..4].try_into().unwrap_or([0; 4]));
        let aes_out = match aes_decrypt(cipher, iv, k_raw, car_key) {
            Ok(v) => v,
            Err(_) => continue,
        };

        let mut d_copy = d_blob.clone();
        xor_in_place(&mut d_copy, &aes_out);

        if let Some(dds) = try_zlib_decompress(&d_copy) {
            if dds.len() >= 4 {
                result.insert(name.clone(), dds);
            }
        }
    }
    Ok(result)
}

// ── vertex masks ─────────────────────────────────────────────────────

fn decrypt_vertex_masks(
    sidecar: &HashMap<String, Vec<u8>>,
    car_key: &str,
    enc_version: u32,
) -> Result<HashMap<String, (Vec<u8>, f32)>> {
    let mut result = HashMap::new();
    let mut names: Vec<String> = Vec::new();
    for k in sidecar.keys() {
        if let Some(rest) = k.strip_prefix("ver.") {
            if let Some(name) = rest.strip_suffix(".k") {
                if !names.contains(&name.to_string()) {
                    names.push(name.to_string());
                }
            }
        }
    }

    for name in &names {
        let Some(k_bytes) = sidecar.get(&format!("ver.{name}.k")) else { continue };
        let Some(iv) = sidecar.get(&format!("ver.{name}.i")) else { continue };
        let Some(cipher) = sidecar.get(&format!("ver.{name}.x")) else { continue };

        let delta = if enc_version != 1 {
            let Some(f) = sidecar.get(&format!("ver.{name}.f")) else { continue };
            if f.len() < 4 { continue; }
            f32::from_le_bytes(f[..4].try_into().unwrap())
        } else {
            0.03
        };

        let k_raw = u32::from_le_bytes(k_bytes[..4].try_into().unwrap_or([0; 4]));
        let mask = match aes_decrypt(cipher, iv, k_raw, car_key) {
            Ok(v) => v,
            Err(_) => continue,
        };
        result.insert(name.clone(), (mask, delta));
    }
    Ok(result)
}

// ── salt resolution ──────────────────────────────────────────────────

fn resolve_salt(sidecar: &HashMap<String, Vec<u8>>, candidates: &[String]) -> Option<String> {
    // try textures first
    for k in sidecar.keys() {
        let Some(rest) = k.strip_prefix("tex.") else { continue };
        let Some(name) = rest.strip_suffix(".k") else { continue };
        let ki = format!("tex.{name}.i");
        let kx = format!("tex.{name}.x");
        let kd = format!("tex.{name}.d");
        if !sidecar.contains_key(&ki) || !sidecar.contains_key(&kx) || !sidecar.contains_key(&kd) {
            continue;
        }
        let k_raw = u32::from_le_bytes(sidecar[k][..4].try_into().ok()?);
        let iv = &sidecar[&ki];
        let cipher = &sidecar[&kx];
        let d_blob = &sidecar[&kd];

        for salt in candidates {
            if let Ok(aes_out) = aes_decrypt(cipher, iv, k_raw, salt) {
                let mut d_copy = d_blob.clone();
                xor_in_place(&mut d_copy, &aes_out);
                if let Some(dds) = try_zlib_decompress(&d_copy) {
                    if dds.len() >= 4 {
                        return Some(salt.clone());
                    }
                }
            }
        }
    }
    // then vertex masks
    let mut ver_names: Vec<String> = Vec::new();
    for k in sidecar.keys() {
        if let Some(rest) = k.strip_prefix("ver.") {
            if let Some(name) = rest.strip_suffix(".k") {
                if sidecar.contains_key(&format!("ver.{name}.i"))
                    && sidecar.contains_key(&format!("ver.{name}.x"))
                {
                    ver_names.push(name.to_string());
                    if ver_names.len() >= 6 { break; }
                }
            }
        }
    }
    if ver_names.is_empty() { return None; }
    for salt in candidates {
        let mut ok = 0usize;
        for name in &ver_names {
            let k_raw = u32::from_le_bytes(
                sidecar[&format!("ver.{name}.k")][..4].try_into().unwrap_or([0; 4]),
            );
            match aes_decrypt(
                &sidecar[&format!("ver.{name}.x")],
                &sidecar[&format!("ver.{name}.i")],
                k_raw,
                salt,
            ) {
                Ok(m) if !m.is_empty() => ok += 1,
                _ => break,
            }
        }
        if ok == ver_names.len() {
            return Some(salt.clone());
        }
    }
    None
}

// ── KN5 body rebuild ─────────────────────────────────────────────────

struct Kn5Body {
    tex_section_start: usize,
    tex_section_end: usize,
    body_end: usize,
    textures: Vec<TexEntry>,
    meshes: Vec<MeshEntry>,
}

struct TexEntry {
    active: i32,
    name: String,
    body_offset: usize,
    body_length: usize,
}

struct MeshEntry {
    name: String,
    vertex_buffer_offset: usize,
    vertex_count: usize,
    stride: usize,
}

fn parse_kn5_body(buf: &[u8]) -> Result<Kn5Body> {
    if buf.len() < 14 || &buf[0..6] != b"sc6969" {
        bail!("not a KN5 body");
    }
    let mut pos = 6usize;
    let version = ri32(buf, &mut pos);
    if version > 5 { pos += 4; }

    let tex_section_start = pos;
    let tex_count = ri32(buf, &mut pos) as usize;
    let mut textures = Vec::with_capacity(tex_count);
    for _ in 0..tex_count {
        let active = ri32(buf, &mut pos);
        if active == 0 {
            textures.push(TexEntry { active, name: String::new(), body_offset: 0, body_length: 0 });
            continue;
        }
        let name = rstring(buf, &mut pos)?;
        let body_length = ru32(buf, &mut pos) as usize;
        let body_offset = pos;
        pos += body_length;
        textures.push(TexEntry { active, name, body_offset, body_length });
    }
    let tex_section_end = pos;

    let mat_count = ri32(buf, &mut pos) as usize;
    for _ in 0..mat_count {
        skip_string(buf, &mut pos);
        skip_string(buf, &mut pos);
        pos += 6;
        let prop_count = ri32(buf, &mut pos) as usize;
        for _ in 0..prop_count { skip_string(buf, &mut pos); pos += 40; }
        let map_count = ri32(buf, &mut pos) as usize;
        for _ in 0..map_count { skip_string(buf, &mut pos); pos += 4; skip_string(buf, &mut pos); }
    }

    let mut meshes = Vec::new();
    read_node(buf, &mut pos, &mut meshes)?;
    let body_end = pos;

    Ok(Kn5Body { tex_section_start, tex_section_end, body_end, textures, meshes })
}

fn read_node(buf: &[u8], pos: &mut usize, meshes: &mut Vec<MeshEntry>) -> Result<()> {
    let class = ri32(buf, pos);
    let name = rstring(buf, pos)?;
    let child_count = ri32(buf, pos) as usize;
    *pos += 1; // active
    match class {
        0 => {}
        1 => { *pos += 64; }
        2 => {
            *pos += 3;
            let vert_count = ru32(buf, pos) as usize;
            meshes.push(MeshEntry { name, vertex_buffer_offset: *pos, vertex_count: vert_count, stride: 44 });
            *pos += vert_count * 44;
            let idx_count = ru32(buf, pos) as usize;
            *pos += idx_count * 2;
            *pos += 4 + 4 + 4 + 4 + 12 + 4 + 1;
        }
        3 => {
            *pos += 3;
            let bone_count = ru32(buf, pos) as usize;
            for _ in 0..bone_count { skip_string(buf, pos); *pos += 64; }
            let vert_count = ru32(buf, pos) as usize;
            meshes.push(MeshEntry { name, vertex_buffer_offset: *pos, vertex_count: vert_count, stride: 76 });
            *pos += vert_count * 76;
            let idx_count = ru32(buf, pos) as usize;
            *pos += idx_count * 2;
            *pos += 4 + 4 + 8;
        }
        _ => bail!("unknown node class {class} at 0x{:X}", *pos - 4),
    }
    for _ in 0..child_count {
        read_node(buf, pos, meshes)?;
    }
    Ok(())
}

fn rebuild_kn5(
    body: &[u8],
    textures: &HashMap<String, Vec<u8>>,
    masks: &HashMap<String, (Vec<u8>, f32)>,
) -> Result<Vec<u8>> {
    let parsed = parse_kn5_body(body)?;
    let mut body_mut = body.to_vec();

    // apply vertex masks
    for mesh in &parsed.meshes {
        if let Some((mask, delta)) = masks.get(&mesh.name) {
            apply_mask(&mut body_mut, mesh, mask, *delta);
        }
    }

    let mut out = Vec::with_capacity(body.len());
    out.extend_from_slice(&body_mut[..parsed.tex_section_start]);

    // rewrite texture section with decrypted textures
    let mut tw = Cursor::new(Vec::new());
    wi32(&mut tw, parsed.textures.len() as i32);
    for t in &parsed.textures {
        wi32(&mut tw, t.active);
        if t.active == 0 { continue; }
        wstring(&mut tw, &t.name);
        let data = textures.get(&t.name)
            .map(|v| v.as_slice())
            .unwrap_or(&body_mut[t.body_offset..t.body_offset + t.body_length]);
        wu32(&mut tw, data.len() as u32);
        tw.write_all(data).unwrap();
    }
    out.extend_from_slice(&tw.into_inner());

    // everything after textures (materials + nodes)
    out.extend_from_slice(&body_mut[parsed.tex_section_end..parsed.body_end]);
    Ok(out)
}

fn apply_mask(body: &mut [u8], mesh: &MeshEntry, mask: &[u8], delta: f32) {
    if mask.is_empty() { return; }
    for i in 0..mesh.vertex_count {
        let b = mask[i % mask.len()];
        let o = mesh.vertex_buffer_offset + i * mesh.stride;
        if o + 32 > body.len() { break; }
        add_f(body, o, if b & 1 != 0 { -delta } else { delta });
        add_f(body, o + 4, if b & 2 != 0 { -delta } else { delta });
        add_f(body, o + 8, if b & 4 != 0 { -delta } else { delta });
        if b & 8 != 0 { neg_f(body, o + 12); }
        if b & 16 != 0 { neg_f(body, o + 16); }
        if b & 32 != 0 { neg_f(body, o + 20); }
        if b & 64 != 0 { inv_f(body, o + 24); }
        if b & 128 != 0 { inv_f(body, o + 28); }
    }
}

fn add_f(b: &mut [u8], o: usize, d: f32) {
    let v = f32::from_le_bytes(b[o..o + 4].try_into().unwrap()) + d;
    b[o..o + 4].copy_from_slice(&v.to_le_bytes());
}
fn neg_f(b: &mut [u8], o: usize) {
    let v = -f32::from_le_bytes(b[o..o + 4].try_into().unwrap());
    b[o..o + 4].copy_from_slice(&v.to_le_bytes());
}
fn inv_f(b: &mut [u8], o: usize) {
    let v = 1.0 - f32::from_le_bytes(b[o..o + 4].try_into().unwrap());
    b[o..o + 4].copy_from_slice(&v.to_le_bytes());
}

// ── binary helpers ───────────────────────────────────────────────────

fn ri32(b: &[u8], p: &mut usize) -> i32 {
    let v = i32::from_le_bytes(b[*p..*p + 4].try_into().unwrap());
    *p += 4; v
}
fn ru32(b: &[u8], p: &mut usize) -> u32 {
    let v = u32::from_le_bytes(b[*p..*p + 4].try_into().unwrap());
    *p += 4; v
}
fn rstring(b: &[u8], p: &mut usize) -> Result<String> {
    let n = ru32(b, p) as usize;
    let s = std::str::from_utf8(&b[*p..*p + n])?.to_string();
    *p += n; Ok(s)
}
fn skip_string(b: &[u8], p: &mut usize) {
    let n = u32::from_le_bytes(b[*p..*p + 4].try_into().unwrap()) as usize;
    *p += 4 + n;
}
fn wi32(w: &mut Cursor<Vec<u8>>, v: i32) { w.write_all(&v.to_le_bytes()).unwrap(); }
fn wu32(w: &mut Cursor<Vec<u8>>, v: u32) { w.write_all(&v.to_le_bytes()).unwrap(); }
